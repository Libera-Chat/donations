import Stripe from 'stripe'
import { STRIPE_SECRET_KEY } from '../config.js'

let stripe: Stripe | undefined
export function getStripe () {
  stripe ??= new Stripe(STRIPE_SECRET_KEY, {
    apiVersion: '2025-10-29.clover',
  })
  return stripe
}

